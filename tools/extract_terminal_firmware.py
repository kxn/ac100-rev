#!/usr/bin/env python3
"""Generate recognition data from the supplied V6 firmware, without running it."""
import hashlib
import json
import pathlib
import subprocess
from audit_mobility_firmware import ELF32BE, ROOT, UAC_SHA256

root = ROOT / ".local/ac100/rootfs"
elf = ELF32BE(root / "usr/sbin/uac", UAC_SHA256)

def names(address, count):
    return [elf.read(elf.u32(address + 4*i), 40).split(b"\0")[0].decode() for i in range(count)]

brands, systems = names(0x8f53c4, 10), names(0x8f53ac, 6)
feature_path = root / "etc/terminal_feature.json"
features = json.loads(feature_path.read_text())
q = lambda x: json.dumps(x, ensure_ascii=False)
out = ["// Code generated by tools/extract_terminal_firmware.py; DO NOT EDIT.",
       f"// UAC SHA256 {UAC_SHA256}",
       *[f"// {p.name} SHA256 {hashlib.sha256(p.read_bytes()).hexdigest()}" for p in (feature_path,)],
       "package terminal", "var brandNames = [...]string{" + ",".join(map(q, brands)) + "}",
       "var systemNames = [...]string{" + ",".join(map(q, systems)) + "}"]
for name, address, count in (("brandPriority", 0x8f535c, 10), ("systemPriority", 0x8f5338, 6)):
    out += [f"var {name} = [...][5]byte{{" + ",".join("{"+",".join(map(str, elf.read(address+6*i+1, 5)))+"}" for i in range(count)) + "}"]
for kind, keys in (("host_name", brands), ("class_identify", systems), ("http_ua", systems)):
    out += [f"var {kind} = []feature{{"]
    for index, key in enumerate(keys[1:], 1):
        for value in features[kind].get(key, []):
            out += [f"{{{q(value)},{index}}},"]
    out += ["}"]
# OUI lookup is supplied by the complete IEEE registry, not this firmware table.
target = ROOT / "uacgo/terminal/tables_generated.go"
target.parent.mkdir(exist_ok=True)
target.write_text(subprocess.check_output(["gofmt"], input="\n".join(out)+"\n", text=True))
print("Generated firmware hostname/Class/UA rules and priorities; IEEE supplies OUI data")
